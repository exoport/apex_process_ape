// pinProject makes repo/.git and repo/.bingo/ape.mod pinning version, and
// returns repo/sub — a directory inside it, so the walk-up is exercised.
func pinProject(t *testing.T, version string) (root, sub string) {
	t.Helper()
	root = t.TempDir()
	require.NoError(t, os.MkdirAll(filepath.Join(root, ".git"), 0o755))
	if version != "" {
		require.NoError(t, os.MkdirAll(filepath.Join(root, ".bingo"), 0o755))
		mod := "module _ // Auto generated by https://github.com/bwplotka/bingo. DO NOT EDIT\n\n" +
			"go 1.27.0\n\nrequire github.com/exoport/apex_process_ape " + version + " // cmd/ape\n"
		require.NoError(t, os.WriteFile(filepath.Join(root, ".bingo", "ape.mod"), []byte(mod), 0o644))
	}
	sub = filepath.Join(root, "a", "b")
	require.NoError(t, os.MkdirAll(sub, 0o755))
	return root, sub
}

func pinInput(cwd, running, verb string) pinCheckInput {
	return pinCheckInput{
		cwd: cwd, running: running, self: "/path/to/ape-running", verb: verb,
		env:       func(string) string { return "" },
		locate:    func(v string) (string, bool) { return "/gobin/ape-" + v, true },
		floorFrom: func(string) (string, error) { return "", errors.New("no floor") },
	}
}

// TestDecidePin is the walk-through the framework session agreed, step by
// step: no pin runs as before; a matching pin runs; a different pin swaps;
// an uninstalled or pre-floor pin refuses — except for the verbs a project
// recovers with — and never silently runs this binary instead.
func TestDecidePin(t *testing.T) {
	t.Run("no pin: today's behaviour", func(t *testing.T) {
		_, sub := pinProject(t, "")
		d := decidePin(pinInput(sub, "0.7.0", "ape story list"))
		require.True(t, d.run)
		require.Empty(t, d.note)
	})
	t.Run("pin equals this ape: run", func(t *testing.T) {
		_, sub := pinProject(t, "v0.8.4")
		d := decidePin(pinInput(sub, "0.8.4", "ape story list"))
		require.True(t, d.run)
	})
	t.Run("pin differs: swap to the pinned binary", func(t *testing.T) {
		_, sub := pinProject(t, "v0.8.4")
		d := decidePin(pinInput(sub, "0.7.0", "ape story list"))
		require.False(t, d.run)
		require.Equal(t, "/gobin/ape-v0.8.4", d.exec)
	})
	t.Run("a dev build is swapped too", func(t *testing.T) {
		_, sub := pinProject(t, "v0.8.4")
		d := decidePin(pinInput(sub, "dev", "ape story list"))
		require.Equal(t, "/gobin/ape-v0.8.4", d.exec)
	})
	t.Run("pin not installed: refuse, never fall back", func(t *testing.T) {
		_, sub := pinProject(t, "v0.8.4")
		in := pinInput(sub, "0.7.0", "ape story list")
		in.locate = func(string) (string, bool) { return "", false }
		d := decidePin(in)
		require.False(t, d.run)
		require.Empty(t, d.exec)
		require.ErrorContains(t, d.refuse, "pins ape v0.8.4")
		require.ErrorContains(t, d.refuse, "not installed")
		require.ErrorContains(t, d.refuse, "bingo get ape")
		require.ErrorContains(t, d.refuse, envToolchain+"=local")
	})
	t.Run("pin below the framework floor: refuse with the move-forward command", func(t *testing.T) {
		root, sub := pinProject(t, "v0.0.66")
		in := pinInput(sub, "0.7.0", "ape story list")
		in.floorFrom = func(r string) (string, error) {
			require.Equal(t, root, r)
			return "0.7.0", nil
		}
		d := decidePin(in)
		require.ErrorContains(t, d.refuse, "pins ape v0.0.66")
		require.ErrorContains(t, d.refuse, "min_ape_version 0.7.0")
		require.ErrorContains(t, d.refuse, "bingo get -l "+apeModulePath+"@v0.7.0")
	})
	t.Run("recovery verbs run here with a note", func(t *testing.T) {
		for _, verb := range []string{"ape framework update", "ape doctor", "ape version", "ape"} {
			_, sub := pinProject(t, "v0.0.66")
			in := pinInput(sub, "0.8.5", verb)
			in.floorFrom = func(string) (string, error) { return "0.7.0", nil }
			d := decidePin(in)
			require.True(t, d.run, verb)
			require.NoError(t, d.refuse, verb)
			require.Contains(t, d.note, "running ape 0.8.5 instead", verb)
		}
	})
	t.Run("help runs here when the pin cannot", func(t *testing.T) {
		_, sub := pinProject(t, "v0.8.4")
		in := pinInput(sub, "0.7.0", "ape story list")
		in.help = true
		in.locate = func(string) (string, bool) { return "", false }
		require.True(t, decidePin(in).run)
	})
	t.Run("recovery verbs still swap when the pin is usable", func(t *testing.T) {
		_, sub := pinProject(t, "v0.8.4")
		d := decidePin(pinInput(sub, "0.7.0", "ape doctor"))
		require.Equal(t, "/gobin/ape-v0.8.4", d.exec)
	})
	t.Run("ape update never swaps: it updates the launcher", func(t *testing.T) {
		_, sub := pinProject(t, "v0.8.4")
		d := decidePin(pinInput(sub, "0.7.0", "ape update"))
		require.True(t, d.run)
		require.Empty(t, d.exec)
	})
	t.Run("framework update --update-ape runs on the launcher", func(t *testing.T) {
		// It moves the pin first; handing it to a pin older than 0.9.0
		// failed with "unknown flag: --update-ape".
		_, sub := pinProject(t, "v0.8.3")
		in := pinInput(sub, "0.9.0", verbFrameworkUpdate)
		in.updateApe = true
		d := decidePin(in)
		require.True(t, d.run)
		require.Empty(t, d.exec)

		in.updateApe = false
		require.Equal(t, "/gobin/ape-v0.8.3", decidePin(in).exec, "without the flag it is handed over as usual")
	})
	t.Run("escape hatch", func(t *testing.T) {
		_, sub := pinProject(t, "v0.8.4")
		in := pinInput(sub, "0.7.0", "ape story list")
		in.env = func(k string) string {
			if k == envToolchain {
				return "local"
			}
			return ""
		}
		d := decidePin(in)
		require.True(t, d.run)
		require.Empty(t, d.note)
	})
	t.Run("loop guard: a swapped-to binary runs whatever it reports", func(t *testing.T) {
		_, sub := pinProject(t, "v0.8.4")
		in := pinInput(sub, "0.8.4-weird", "ape story list")
		in.env = func(k string) string {
			if k == envPinned {
				return "v0.8.4"
			}
			return ""
		}
		require.True(t, decidePin(in).run)
	})
	t.Run("loop guard: the pin is this very binary", func(t *testing.T) {
		_, sub := pinProject(t, "v0.8.4")
		in := pinInput(sub, "0.8.4-weird", "ape story list")
		in.locate = func(string) (string, bool) { return in.self, true }
		require.True(t, decidePin(in).run)
	})
	t.Run("an inherited marker for another pin does not skip the check", func(t *testing.T) {
		_, sub := pinProject(t, "v0.8.4")
		in := pinInput(sub, "0.7.0", "ape story list")
		in.env = func(k string) string {
			if k == envPinned {
				return "v0.8.2"
			}
			return ""
		}
		require.Equal(t, "/gobin/ape-v0.8.4", decidePin(in).exec)
	})
	t.Run("an unreadable pin refuses rather than guessing", func(t *testing.T) {
		root, sub := pinProject(t, "")
		require.NoError(t, os.MkdirAll(filepath.Join(root, ".bingo"), 0o755))
		require.NoError(t, os.WriteFile(filepath.Join(root, ".bingo", "ape.mod"), []byte("module _\nrequire other/mod v1.0.0\n"), 0o644))
		d := decidePin(pinInput(sub, "0.7.0", "ape story list"))
		require.ErrorContains(t, d.refuse, "requires no "+apeModuleRoot)
	})
	t.Run("outside any repo, a pin above is not honoured", func(t *testing.T) {
		// ~/_dev/.bingo/ape.mod installs a launcher; ~/_dev/exoar below it
		// is not a repo, and must not be swapped to that pin.
		top := t.TempDir()
		require.NoError(t, os.MkdirAll(filepath.Join(top, ".bingo"), 0o755))
		require.NoError(t, os.WriteFile(filepath.Join(top, ".bingo", "ape.mod"),
			[]byte("module _\nrequire github.com/exoport/apex_process_ape v0.7.0 // cmd/ape\n"), 0o644))
		below := filepath.Join(top, "exoar")
		require.NoError(t, os.MkdirAll(below, 0o755))

		for _, dir := range []string{below, top} {
			d := decidePin(pinInput(dir, "0.9.0", "ape story list"))
			require.True(t, d.run, dir)
			require.Empty(t, d.exec, dir)
		}
	})
	t.Run("a worktree's .git file marks the repo root", func(t *testing.T) {
		root := t.TempDir()
		require.NoError(t, os.WriteFile(filepath.Join(root, ".git"), []byte("gitdir: /elsewhere\n"), 0o644))
		require.NoError(t, os.MkdirAll(filepath.Join(root, ".bingo"), 0o755))
		require.NoError(t, os.WriteFile(filepath.Join(root, ".bingo", "ape.mod"),
			[]byte("module _\nrequire github.com/exoport/apex_process_ape v0.8.4 // cmd/ape\n"), 0o644))
		d := decidePin(pinInput(root, "0.7.0", "ape story list"))
		require.Equal(t, "/gobin/ape-v0.8.4", d.exec)
	})
	t.Run("the walk stops at the repo root", func(t *testing.T) {
		outer, _ := pinProject(t, "v0.8.4")
		inner := filepath.Join(outer, "nested")
		require.NoError(t, os.MkdirAll(filepath.Join(inner, ".git"), 0o755))
		d := decidePin(pinInput(inner, "0.7.0", "ape story list"))
		require.True(t, d.run, "a nested repo with no pin of its own is not the outer repo's project")
	})
}

// L1: every lift rehearsal stopped on the pin swap — the project pins a
// v0 ape, which has no `project` command (or is not installed). The lift
// runs on the binary invoked, however the pin reads.
func TestDecidePin_ProjectLiftIsExempt(t *testing.T) {
	_, sub := pinProject(t, "v0.9.0")
	in := pinInput(sub, "1.0.0-rc.3", verbProjectLift)
	d := decidePin(in)
	require.True(t, d.run)
	require.Empty(t, d.exec)
	in.locate = func(string) (string, bool) { return "", false }
	d = decidePin(in)
	require.True(t, d.run, "not installed: still runs here")
	require.Nil(t, d.refuse)
	require.Equal(t, "/gobin/ape-v0.9.0", decidePin(pinInput(sub, "1.0.0-rc.3", "ape project check")).exec, "other v1 verbs still honour the pin")
}
