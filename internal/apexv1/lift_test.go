func TestLift_Refusals(t *testing.T) {
	t.Run("no tag", func(t *testing.T) {
		root := liftFixture(t, false)
		_, err := Lift(ctx(), root, LiftOptions{})
		require.Equal(t, "lift.no-tag", liftCode(err))
	})
	t.Run("tag not at HEAD", func(t *testing.T) {
		root := liftFixture(t, true)
		require.NoError(t, os.WriteFile(filepath.Join(root, "x.txt"), []byte("x"), 0o644))
		run(t, root, "add", "x.txt")
		run(t, root, "commit", "-q", "-m", "after the tag")
		_, err := Lift(ctx(), root, LiftOptions{})
		require.Equal(t, "lift.tag-not-head", liftCode(err))
	})
	t.Run("tag not pushed", func(t *testing.T) {
		root := liftFixture(t, false)
		run(t, root, "tag", "-a", LiftTag, "-m", "final")
		_, err := Lift(ctx(), root, LiftOptions{})
		require.Equal(t, "lift.tag-not-pushed", liftCode(err))
		require.Contains(t, err.Error(), "is not on origin")
	})
	t.Run("tag pushed at another commit", func(t *testing.T) {
		root := liftFixture(t, true)
		require.NoError(t, os.WriteFile(filepath.Join(root, "x.txt"), []byte("x"), 0o644))
		run(t, root, "add", "x.txt")
		run(t, root, "commit", "-q", "-m", "after the tag")
		run(t, root, "tag", "-f", "-a", LiftTag, "-m", "moved")
		_, err := Lift(ctx(), root, LiftOptions{})
		require.Equal(t, "lift.tag-not-pushed", liftCode(err))
		require.Contains(t, err.Error(), "on origin is")
	})
	t.Run("no upstream remote", func(t *testing.T) {
		root := liftFixture(t, true)
		run(t, root, "branch", "--unset-upstream")
		_, err := Lift(ctx(), root, LiftOptions{})
		require.Equal(t, "lift.tag-not-pushed", liftCode(err))
		require.Contains(t, err.Error(), "no upstream remote")
	})
	t.Run("dirty", func(t *testing.T) {
		root := liftFixture(t, true)
		require.NoError(t, os.WriteFile(filepath.Join(root, "main.go"), []byte("package main\n"), 0o644))
		_, err := Lift(ctx(), root, LiftOptions{})
		require.Equal(t, "lift.dirty", liftCode(err))
		require.Contains(t, err.Error(), "main.go")
	})
	t.Run("not v0", func(t *testing.T) {
		root := liftFixture(t, true)
		run(t, root, "rm", "-q", "-r", "_apex", "development")
		run(t, root, "commit", "-q", "-m", "no apex")
		_, err := Lift(ctx(), root, LiftOptions{})
		require.Equal(t, "lift.not-v0", liftCode(err))
	})
	t.Run("v0 config without a framework record", func(t *testing.T) {
		root := liftFixture(t, true)
		run(t, root, "rm", "-q", "_apex/framework.yaml")
		run(t, root, "commit", "-q", "-m", "no record")
		_, err := Lift(ctx(), root, LiftOptions{})
		require.Equal(t, "lift.unsupported-layout", liftCode(err))
		require.Contains(t, err.Error(), "v0 folder keys")
	})
	t.Run("too old", func(t *testing.T) {
		root := liftFixture(t, true)
		require.NoError(t, os.WriteFile(filepath.Join(root, "_apex", "framework.yaml"),
			[]byte(strings.Replace(liftFrameworkYAML, "v0.30.0", "v0.14.2", 1)), 0o644))
		run(t, root, "commit", "-q", "-am", "old")
		_, err := Lift(ctx(), root, LiftOptions{})
		require.Equal(t, "lift.unsupported-layout", liftCode(err))
		require.Contains(t, err.Error(), "v0.14.2")
	})
	t.Run("already v1", func(t *testing.T) {
		root := liftFixture(t, true)
		require.NoError(t, os.MkdirAll(filepath.Join(root, "_apex", "state"), 0o755))
		_, err := Lift(ctx(), root, LiftOptions{})
		require.Equal(t, "lift.not-v0", liftCode(err))
		require.Contains(t, err.Error(), "APEX v1 already")
	})
	t.Run("bad exclude", func(t *testing.T) {
		root := liftFixture(t, true)
		_, err := Lift(ctx(), root, LiftOptions{Exclude: []string{"[x"}})
		require.Equal(t, "usage.lift-exclude", liftCode(err))
	})
}

// Inside `ape framework update`: the v1 install has already written its
// skills and framework.yaml, uncommitted. The lift leaves those to the
// install's commit and still deletes the v0 skills.
func TestLift_FromUpdate(t *testing.T) {
	root := liftFixture(t, true)
	v1 := strings.NewReplacer("v0.30.0", "v1.0.0", "      - .claude/skills/apex-dev-story\n", "      - .claude/skills/apex-plan\n").Replace(liftFrameworkYAML)
	require.NoError(t, os.WriteFile(filepath.Join(root, "_apex", "framework.yaml"), []byte(v1), 0o644))
	require.NoError(t, os.RemoveAll(filepath.Join(root, ".claude", "skills", "apex-dev-story")))
	require.NoError(t, os.WriteFile(filepath.Join(root, ".claude", "skills", "apex-orchestrator", "SKILL.md"), []byte("---\nname: apex-orchestrator\nv1: true\n---\n"), 0o644))
	require.NoError(t, os.MkdirAll(filepath.Join(root, ".claude", "skills", "apex-plan"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(root, ".claude", "skills", "apex-plan", "SKILL.md"), []byte("v1\n"), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(root, "_apex", "ape-commands.yaml"), []byte("min_ape_version: 1.0.0\n"), 0o644))
	require.NoError(t, os.MkdirAll(filepath.Join(root, "_apex", "migrations"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(root, "_apex", "migrations", "v1.0.0_seq-01_lift.md"), []byte("---\nid: x\n---\n"), 0o644))
	require.NoError(t, os.MkdirAll(filepath.Join(root, "_apex", "standards"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(root, filepath.FromSlash(StandardADRPayload)), []byte(payloadStandard), 0o644))

	_, err := Lift(ctx(), root, LiftOptions{NoVerifyRun: true})
	require.Equal(t, "lift.dirty", liftCode(err), "a person's lift needs a clean tree")

	res, err := Lift(ctx(), root, LiftOptions{FromUpdate: true, NoVerifyRun: true})
	require.NoError(t, err)
	require.Equal(t, "v0.30.0", res.Version)
	require.Contains(t, res.VersionSource, "_apex/framework.yaml at ")
	committed := run(t, root, "show", "--name-status", "--format=", "HEAD")
	require.Contains(t, committed, "D\t.claude/skills/apex-dev-story/SKILL.md")
	require.NotContains(t, committed, "apex-orchestrator")
	require.NotContains(t, committed, "_apex/ape-commands.yaml")
	require.NotContains(t, committed, "_apex/framework.yaml")
	// What remains uncommitted is exactly the install's.
	var status []string
	for l := range strings.SplitSeq(run(t, root, "status", "--porcelain"), "\n") {
		status = append(status, strings.TrimSpace(l))
	}
	slices.Sort(status)
	require.Equal(t, []string{
		"?? .claude/skills/apex-plan/", "?? _apex/migrations/", "?? _apex/standards/",
		"M .claude/skills/apex-orchestrator/SKILL.md", "M _apex/ape-commands.yaml", "M _apex/framework.yaml",
	}, status)
	require.FileExists(t, filepath.Join(root, ".claude", "skills", "apex-plan", "SKILL.md"))
	require.Equal(t, "lift", mustRecord(t, root, "ADR-0002").By)
	// The standard is the installed payload's, recorded with its version;
	// the payload file itself is the install's to commit (D205 Q117, D206).
	std := mustRecord(t, root, "ADR-0001")
	require.Equal(t, StandardBy("ape project lift"), std.By)
	require.Equal(t, &StandardRecord{FrameworkVersion: "v1.0.0", SHA256: bytesSHA256(payloadStandard)}, std.Standard)
	require.Equal(t, payloadStandard, read(t, &Project{Root: root}, "development/decisions/"+StandardADRFile()))
	require.Equal(t, StandardADRPayload, res.StandardADR.Source)
}

