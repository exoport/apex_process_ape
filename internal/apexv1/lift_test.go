// Inside `ape framework update`: the v1 install has already written its
// skills and framework.yaml, uncommitted. The lift leaves those to the
// install's commit and still deletes the v0 skills.
func TestLift_FromUpdate(t *testing.T) {
	root := liftFixture(t, true)
	v1 := strings.NewReplacer("v0.30.0", "v1.0.0", "      - .claude/skills/apex-dev-story\n", "      - .claude/skills/apex-plan\n").Replace(liftFrameworkYAML)
	require.NoError(t, os.WriteFile(filepath.Join(root, "_apex/framework.yaml"), []byte(v1), 0o644))
	require.NoError(t, os.RemoveAll(filepath.Join(root, ".claude/skills/apex-dev-story")))
	require.NoError(t, os.WriteFile(filepath.Join(root, ".claude/skills/apex-orchestrator/SKILL.md"), []byte("---\nname: apex-orchestrator\nv1: true\n---\n"), 0o644))
	require.NoError(t, os.MkdirAll(filepath.Join(root, ".claude/skills/apex-plan"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(root, ".claude/skills/apex-plan/SKILL.md"), []byte("v1\n"), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(root, "_apex/ape-commands.yaml"), []byte("min_ape_version: 1.0.0\n"), 0o644))
	require.NoError(t, os.MkdirAll(filepath.Join(root, "_apex/migrations"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(root, "_apex/migrations/v1.0.0_seq-01_lift.md"), []byte("---\nid: x\n---\n"), 0o644))

	_, err := Lift(ctx(), root, LiftOptions{NoVerifyRun: true})
	require.Equal(t, "lift.dirty", liftCode(err), "a person's lift needs a clean tree")

	res, err := Lift(ctx(), root, LiftOptions{FromUpdate: true, NoVerifyRun: true})
	require.NoError(t, err)
	require.Equal(t, "v0.30.0", res.Version)
	require.Contains(t, res.VersionSource, "_apex/framework.yaml at ")
	committed := run(t, root, "show", "--name-status", "--format=", "HEAD")
	require.Contains(t, committed, "D\t.claude/skills/apex-dev-story/SKILL.md")
	require.NotContains(t, committed, "apex-orchestrator")
	require.NotContains(t, committed, "_apex/ape-commands.yaml")
	require.NotContains(t, committed, "_apex/framework.yaml")
	// What remains uncommitted is exactly the install's.
	var status []string
	for l := range strings.SplitSeq(run(t, root, "status", "--porcelain"), "\n") {
		status = append(status, strings.TrimSpace(l))
	}
	slices.Sort(status)
	require.Equal(t, []string{
		"?? .claude/skills/apex-plan/", "?? _apex/migrations/",
		"M .claude/skills/apex-orchestrator/SKILL.md", "M _apex/ape-commands.yaml", "M _apex/framework.yaml",
	}, status)
	require.FileExists(t, filepath.Join(root, ".claude/skills/apex-plan/SKILL.md"))
	require.Equal(t, "lift", mustRecord(t, root, "ADR-0001").By)
}

func mustRecord(t *testing.T, root, id string) DecisionRecord {
	t.Helper()
	var recs map[string]DecisionRecord
	data, err := os.ReadFile(filepath.Join(root, "_apex", "state", "decisions.json"))
	require.NoError(t, err)
	require.NoError(t, json.Unmarshal(data, &recs))
	return recs[id]
}

// A canon ADR the project cites and has no record of is copied from the
// governance clone, numbered after the local ones.
func TestLift_CanonADRs(t *testing.T) {
	root := liftFixture(t, false)
	gov := t.TempDir()
	require.NoError(t, os.MkdirAll(filepath.Join(gov, "adrs"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(gov, "adrs", "adr-0070_org-wide-rule.md"),
		[]byte("---\nid: ADR-0070\nstatus: accepted\ntitle: Org-wide rule\ncreated_at: 2026-01-02\n---\n## Context\nc\n## Decision\nd\n## Consequences\nq\n"), 0o644))
	cfg := read(t, &Project{Root: root}, "_apex/config.yaml")
	require.NoError(t, os.WriteFile(filepath.Join(root, "_apex/config.yaml"), []byte(strings.Replace(cfg, `governance_repository_path: ""`, "governance_repository_path: "+gov, 1)), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(root, "rule.go"), []byte("package main\n\n// Follows ADR-0070 and ADR-0099.\nvar rule = 1\n"), 0o644))
	run(t, root, "add", "-A")
	run(t, root, "commit", "-q", "-m", "cite canon")
	run(t, root, "tag", "-a", LiftTag, "-m", "final")
	run(t, root, "push", "-q", "origin", LiftTag)

	res, err := Lift(ctx(), root, LiftOptions{NoVerifyRun: true})
	require.NoError(t, err)
	last := res.ADRs[len(res.ADRs)-1]
	require.True(t, last.Canon)
	require.Equal(t, "ADR-0070 ADR-0006", last.Old+" "+last.New)
	p, err := Open(root)
	require.NoError(t, err)
	require.Equal(t, "package main\n\n// Follows ADR-0006 and ADR-0099.\nvar rule = 1\n", read(t, p, "rule.go"))
	require.Contains(t, read(t, p, "development/decisions/0006-org-wide-rule.md"), "Lifted from: ADR-0070, adrs/adr-0070_org-wide-rule.md at the governance repository (canon)")
	require.Equal(t, []LiftIDRef{{File: "rule.go", Line: 3, Text: "ADR-0099", Where: "comment"}}, res.UnresolvedCitations)
	require.Contains(t, read(t, p, "development/lift-disposition.md"), "`rule.go:3` `ADR-0099` — comment")
}

