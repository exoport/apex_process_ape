// liftFixture builds the v0 project in a git repo with a bare remote as
// origin, main pushed. tag: apex-v0-final created and pushed.
func liftFixture(t *testing.T, tag bool) string {
	t.Helper()
	needSh(t)
	gitEnv(t)
	t.Setenv("APEX_GOVERNANCE_REPO", "")
	base := t.TempDir()
	root := filepath.Join(base, "proj")
	src := filepath.Join("..", "..", "testdata", "apexproject")
	require.NoError(t, filepath.WalkDir(src, func(path string, d fs.DirEntry, err error) error {
		require.NoError(t, err)
		rel, _ := filepath.Rel(src, path)
		if d.IsDir() {
			return os.MkdirAll(filepath.Join(root, rel), 0o755)
		}
		data, err := os.ReadFile(path)
		require.NoError(t, err)
		return os.WriteFile(filepath.Join(root, rel), data, 0o644)
	}))
	for rel, content := range liftFiles() {
		p := filepath.Join(root, filepath.FromSlash(rel))
		require.NoError(t, os.MkdirAll(filepath.Dir(p), 0o755))
		mode := os.FileMode(0o644)
		if strings.HasSuffix(rel, ".sh") {
			mode = 0o755
		}
		require.NoError(t, os.WriteFile(p, []byte(content), mode))
	}
	tm := filepath.Join(root, "development", "team-memory.md")
	data, err := os.ReadFile(tm)
	require.NoError(t, err)
	require.NoError(t, os.WriteFile(tm, append(data, []byte("\n## Technical Gotchas\n\n### NATS err_code 10164 misses the CAS classifier — 2026-08-03\n\nBody.\n")...), 0o644))
	remote := filepath.Join(base, "remote.git")
	run(t, base, "init", "-q", "--bare", remote)
	run(t, root, "init", "-q", "-b", "main")
	run(t, root, "add", "-A")
	run(t, root, "commit", "-q", "-m", "v0 project")
	run(t, root, "remote", "add", "origin", remote)
	run(t, root, "push", "-q", "-u", "origin", "main")
	if tag {
		run(t, root, "tag", "-a", LiftTag, "-m", "APEX v0 final")
		run(t, root, "push", "-q", "origin", LiftTag)
	}
	return root
}

func liftCode(err error) string {
	if fe, ok := errors.AsType[*FailError](err); ok {
		return fe.Code
	}
	if ue, ok := errors.AsType[*UsageError](err); ok {
		return ue.Code
	}
	return ""
}

// requireLiftedADRs checks TestLift_FullRun's ADRs: renumbered in order,
// superseded and proposed included, each converted to the v1 shape.
func requireLiftedADRs(t *testing.T, p *Project, root string, res *LiftResult) {
	t.Helper()
	olds := make([]string, 0, len(res.ADRs))
	news := make([]string, 0, len(res.ADRs))
	for i := range res.ADRs {
		a := &res.ADRs[i]
		olds = append(olds, a.Old)
		news = append(news, a.New+" "+a.Status)
	}
	// ADR-0001 is the standard, not converted (D205 Q119).
	require.Equal(t, []string{"ADR-0002", "ADR-0004", "ADR-0006", "ADR-0007"}, olds)
	require.Equal(t, []string{"ADR-0002 accepted", "ADR-0003 superseded by ADR-0004", "ADR-0004 accepted", "ADR-0005 proposed"}, news)
	require.Equal(t, &StandardADRResult{
		Action: StandardReplaced, Path: "development/decisions/" + StandardADRFile(), Source: StandardSourceApe,
		Replaces: "ADR-0001, development/governance/adrs/adr-0001_use-markdown-adrs.md",
	}, res.StandardADR)
	require.Equal(t, EmbeddedStandardADR(), read(t, p, "development/decisions/"+StandardADRFile()))
	require.NoFileExists(t, filepath.Join(root, "development", "decisions", "0001-use-markdown-adrs.md"))
	d2 := read(t, p, "development/decisions/0003-limit-names.md")
	require.Equal(t, "# ADR-0003: Limit names\nStatus: superseded by ADR-0004\nDate: "+gitFirstDate(ctx(), root, "development/governance/adrs/adr-0004_limit-names.md")+"\n"+
		"Lifted from: ADR-0004, development/governance/adrs/adr-0004_limit-names.md at apex-v0-final\n\n"+
		"## Context\nNames can be long.\n\n## Decision\nCap at 32.\n\n"+
		"## Consequences\n_Not recorded in the apex-v0 ADR; the section was added at the lift so the record has the apex-v1 shape._\n\nEnforced by: review\n", d2)
	d4 := read(t, p, "development/decisions/0004-limit-64.md")
	require.Contains(t, d4, "# ADR-0004: Limit names to 64\nStatus: accepted\nDate: 2026-09-01\nSupersedes: ADR-0003\n")
	require.Contains(t, d4, "32 was too short; see ADR-0003.")
	require.Contains(t, d4, "Enforced by: go test ./...")
	require.NotContains(t, d4, "Enforced by: review")
	for i := range res.ADRs {
		if a := &res.ADRs[i]; a.Old == "ADR-0004" {
			require.Contains(t, strings.Join(a.Gaps, "\n"), "renamed `## Context`")
			require.Contains(t, strings.Join(a.Gaps, "\n"), "no `## Consequences`")
		}
	}
}

