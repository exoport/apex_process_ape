// TestReconcile_ConcurrentEpicsBothLand is the lock test. Without the
// advisory lock this is a read-modify-write race and one of the two
// updates is silently lost — which is exactly what happens when
// per-epic sub-agents reconcile the same tracker in parallel.
func TestReconcile_ConcurrentEpicsBothLand(t *testing.T) {
	path := writeTracker(t, `development_status:
  epic-1: backlog
  1-1: done
  epic-2: backlog
  2-1: done
`)
	var wg sync.WaitGroup
	errs := make([]error, 2)
	for i, epic := range []int{1, 2} {
		wg.Add(1)
		go func(slot, e int) {
			defer wg.Done()
			_, err := Reconcile(path, ReconcileOptions{Epic: e, Timestamp: "20260401090000"})
			errs[slot] = err
		}(i, epic)
	}
	wg.Wait()
	require.NoError(t, errs[0])
	require.NoError(t, errs[1])

	body, err := os.ReadFile(path)
	require.NoError(t, err)
	require.Contains(t, string(body), "epic-1: done", "epic 1's update survived")
	require.Contains(t, string(body), "epic-2: done", "epic 2's update survived")
}

func TestLockFile_Serialises(t *testing.T) {
	path := filepath.Join(t.TempDir(), "sprint-status.yaml")
	require.NoError(t, os.WriteFile(path, []byte("development_status: {}\n"), 0o644))

	unlock, err := lockFile(path)
	require.NoError(t, err)

	// The goroutine must not call require (testifylint go-require): a
	// failed assertion there would abort the wrong goroutine. It reports
	// through the channel instead.
	acquired := make(chan error, 1)
	go func() {
		unlock2, lockErr := lockFile(path)
		if lockErr == nil {
			unlock2()
		}
		acquired <- lockErr
	}()

	select {
	case <-acquired:
		t.Fatal("the second lock acquired while the first was held")
	case <-time.After(150 * time.Millisecond):
	}
	unlock()
	require.NoError(t, <-acquired, "the second lock acquires once the first releases")
}

