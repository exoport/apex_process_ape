// realTracker is a sprint-status.yaml in the shape the framework writes:
// a generated header of comments, top-level timestamps, then the row map
// with epic rows interleaved.
const realTracker = `# sprint-status.yaml — generated by apex-sprint-sync. Do not hand-edit.
#
# STATUS DEFINITIONS
#   backlog      not started
#   drafted      story file written, not yet developed
#   in-progress  under development
#   review       awaiting review
#   done         reviewed and accepted
#   blocked      cannot proceed
#   cancelled    out of scope
created_at: '20260101000000'
updated_at: '20260301120000'
development_status:
  epic-1: in-progress   # projected, never asserted
  1-1: done
  1-2: done
  epic-2: backlog
  2-1: backlog
  2-2: backlog
  epic-3: in-progress
  3-1: done
  3-2: cancelled
  epic-3-retrospective: done
`

func writeTracker(t *testing.T, body string) string {
	t.Helper()
	dir := t.TempDir()
	path := filepath.Join(dir, "sprint-status.yaml")
	require.NoError(t, os.WriteFile(path, []byte(body), 0o644))
	return path
}

