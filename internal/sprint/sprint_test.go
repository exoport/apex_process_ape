// TestReconcile_ChangesExactlyTwoLines is the targeted-write proof, and
// the test that fails against the obvious unmarshal/re-marshal
// implementation: every comment, the STATUS DEFINITIONS header, the row
// ordering and every untouched row must be byte-identical.
func TestReconcile_ChangesExactlyTwoLines(t *testing.T) {
	path := writeTracker(t, realTracker)
	before, err := os.ReadFile(path)
	require.NoError(t, err)

	// Epic 1's stories are all done, so its row moves in-progress -> done.
	res, err := Reconcile(path, ReconcileOptions{Epic: 1, Timestamp: "20260401090000"})
	require.NoError(t, err)
	require.True(t, res.Written)
	require.Len(t, res.Changes, 1)
	require.Equal(t, "in-progress", res.Changes[0].From)
	require.Equal(t, StatusDone, res.Changes[0].To)

	after, err := os.ReadFile(path)
	require.NoError(t, err)

	beforeLines := strings.Split(string(before), "\n")
	afterLines := strings.Split(string(after), "\n")
	require.Len(t, afterLines, len(beforeLines), "no lines added or removed")

	var changed []int
	for i := range beforeLines {
		if beforeLines[i] != afterLines[i] {
			changed = append(changed, i)
		}
	}
	require.Len(t, changed, 2, "exactly two lines change: the epic row and updated_at")

	text := string(after)
	require.Contains(t, text, "epic-1: done   # projected, never asserted",
		"the row's trailing comment survives")
	require.Contains(t, text, "# STATUS DEFINITIONS", "the generated header survives")
	require.Contains(t, text, "updated_at: '20260401090000'")
	require.Contains(t, text, "created_at: '20260101000000'", "created_at is untouched")
	// Row ordering is preserved, which a re-marshal would alphabetise.
	require.Less(t, strings.Index(text, "epic-2"), strings.Index(text, "2-1"))
}

