// TestVerifyRow_BackwardsWriteAgainstGit is exit 5 — the code two review
// skills branch on. It needs a real commit to compare against.
func TestVerifyRow_BackwardsWriteAgainstGit(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not available")
	}
	ctx := context.Background()
	dir := t.TempDir()
	git := func(args ...string) {
		cmd := exec.CommandContext(ctx, "git", args...)
		cmd.Dir = dir
		cmd.Env = append(os.Environ(),
			"GIT_AUTHOR_NAME=t", "GIT_AUTHOR_EMAIL=t@e", "GIT_COMMITTER_NAME=t", "GIT_COMMITTER_EMAIL=t@e")
		require.NoError(t, cmd.Run(), "git %v", args)
	}
	git("init", "-q")

	path := filepath.Join(dir, "sprint-status.yaml")
	committed := `created_at: '20260101000000'
updated_at: '20260301120000'
development_status:
  1-1: done
`
	require.NoError(t, os.WriteFile(path, []byte(committed), 0o644))
	git("add", ".")
	git("commit", "-qm", "tracker")

	// Now write an EARLIER updated_at: a backwards write.
	backwards := strings.Replace(committed, "20260301120000", "20260201120000", 1)
	require.NoError(t, os.WriteFile(path, []byte(backwards), 0o644))

	res := VerifyRow(ctx, path, "1-1", "done")
	require.Equal(t, VerifyBackwardsWrite, res.Code, res.Message)
	require.Equal(t, "20260301120000", res.Committed)
	require.Equal(t, "20260301120000", res.Clamp, "the repair value is reported, not guessed at")

	// And the forwards case passes.
	forwards := strings.Replace(committed, "20260301120000", "20260401120000", 1)
	require.NoError(t, os.WriteFile(path, []byte(forwards), 0o644))
	require.Equal(t, VerifyOK, VerifyRow(ctx, path, "1-1", "done").Code)
}

